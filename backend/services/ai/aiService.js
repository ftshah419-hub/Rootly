import { getGeminiModel } from '../../config/gemini.js';
import { AIGeneration } from '../../models/AIGeneration.js';
import { AIUsageLog } from '../../models/AIUsageLog.js';

export const executeGeminiPrompt = async ({
  userId,
  feature,
  prompt,
  systemInstruction = '',
  inlineData = null,
  modelName = 'gemini-1.5-flash'
}) => {
  const startTime = Date.now();
  const model = getGeminiModel(modelName);

  // If no Gemini API key configured, return high-quality structured fallback
  if (!model) {
    const fallbackResponse = getSimulatedFallback(feature, prompt);
    const latencyMs = Date.now() - startTime;

    if (userId) {
      await AIUsageLog.create({
        userId,
        endpoint: feature,
        model: 'simulated-fallback',
        requestStatus: 'FALLBACK',
        latencyMs
      });

      await AIGeneration.create({
        userId,
        feature,
        promptSummary: prompt.substring(0, 200),
        responseSummary: JSON.stringify(fallbackResponse).substring(0, 500),
        modelUsed: 'simulated-fallback',
        tokensUsed: 0
      });
    }

    return {
      success: true,
      data: fallbackResponse,
      isSimulated: true,
      disclaimer: 'Advisory suggestion generated by local produce engine.'
    };
  }

  try {
    const parts = [{ text: prompt }];

    if (inlineData) {
      parts.push({
        inlineData: {
          mimeType: inlineData.mimeType || 'image/jpeg',
          data: inlineData.buffer.toString('base64')
        }
      });
    }

    const result = await model.generateContent(parts);
    const responseText = result.response.text();
    const latencyMs = Date.now() - startTime;

    if (userId) {
      await AIUsageLog.create({
        userId,
        endpoint: feature,
        model: modelName,
        requestStatus: 'SUCCESS',
        latencyMs
      });

      await AIGeneration.create({
        userId,
        feature,
        promptSummary: prompt.substring(0, 200),
        responseSummary: responseText.substring(0, 500),
        modelUsed: modelName,
        tokensUsed: result.response.usageMetadata?.totalTokenCount || 0
      });
    }

    return {
      success: true,
      text: responseText,
      isSimulated: false,
      disclaimer: 'All AI suggestions are advisory. Always inspect produce in person before exchange.'
    };
  } catch (error) {
    console.error(`[Gemini AI Error in ${feature}]`, error.message);
    const latencyMs = Date.now() - startTime;

    if (userId) {
      await AIUsageLog.create({
        userId,
        endpoint: feature,
        model: modelName,
        requestStatus: 'ERROR',
        latencyMs,
        errorMessage: error.message
      });
    }

    // Graceful fallback to maintain app functionality
    return {
      success: true,
      data: getSimulatedFallback(feature, prompt),
      isSimulated: true,
      warning: 'Live Gemini service unavailable. Provided heuristic advisory result.'
    };
  }
};

