/**
 * Translation helper function with nested key support (e.g. 'nav.home')
 */
export const getTranslation = (keyPath, lang = 'en', fallback = '') => {
  const currentLang = lang === 'ml' ? 'ml' : 'en';
  const keys = keyPath.split('.');
  let result = translations[currentLang];

  for (const k of keys) {
    if (result && result[k] !== undefined) {
      result = result[k];
    } else {
      // Fallback to English if missing in Malayalam
      let enResult = translations.en;
      for (const ek of keys) {
        if (enResult && enResult[ek] !== undefined) {
          enResult = enResult[ek];
        } else {
          return fallback || keyPath;
        }
      }
      return enResult || fallback || keyPath;
    }
  }

  return result || fallback || keyPath;
};

export default { translations, getTranslation };
